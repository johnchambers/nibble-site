# Run as `nibble-site optimize-images` from a site's folder.
# Generates the responsive WebP variants the site actually serves, from the
# source photos (JPEG or PNG) in src/images/site, and records each image's
# dimensions and available widths in src/_data/images.yml for
# src/_partials/_image.erb.
#
# Keep sources as JPEGs of at most 1600px on the long edge: big enough for
# every variant, small enough to commit.
#
# Run it after adding or replacing a photo, and commit the .webp files and the
# manifest: the production build does not run this (the server has no cwebp).
# Needs `cwebp` (brew install webp) and macOS's `sips`. Pass --force to
# regenerate everything.
require "yaml"

ROOT = Dir.pwd
SOURCE_DIR = File.join(ROOT, "src/images/site")
MANIFEST = File.join(ROOT, "src/_data/images.yml")
WIDTHS = [384, 768, 1024, 1536].freeze
QUALITY = 80

abort "cwebp not found — brew install webp" unless system("which cwebp > /dev/null 2>&1")
force = ARGV.include?("--force")

def dimensions(path)
  out = `sips -g pixelWidth -g pixelHeight #{path.shellescape}`
  [out[/pixelWidth: (\d+)/, 1].to_i, out[/pixelHeight: (\d+)/, 1].to_i]
end

require "shellwords"

sources = Dir[File.join(SOURCE_DIR, "*.{png,jpg,jpeg}")].sort
manifest = sources.to_h do |source|
  name = File.basename(source, ".*")
  width, height = dimensions(source)
  # Every standard width below the photo's own, plus the photo's own width
  # (capped at the largest), so a 640px photo is served at 640, not 384.
  widths = (WIDTHS.select { _1 < width } + [[width, WIDTHS.last].min]).uniq

  widths.each do |w|
    webp = File.join(SOURCE_DIR, "#{name}-#{w}.webp")
    next if !force && File.exist?(webp) && File.mtime(webp) >= File.mtime(source)

    system("cwebp", "-quiet", "-q", QUALITY.to_s, "-m", "6", "-sharp_yuv", "-resize", w.to_s, "0", source, "-o", webp, exception: true)
    puts "#{name}-#{w}.webp  #{File.size(webp) / 1024} KB"
  end

  [name, {"width" => width, "height" => height, "widths" => widths}]
end

File.write(MANIFEST, "# Generated by nibble-site optimize-images — do not edit by hand.\n#{manifest.to_yaml.delete_prefix("---\n")}")
puts "Wrote #{manifest.size} images to #{MANIFEST.delete_prefix("#{ROOT}/")}"
